import assert from 'node:assert/strict';
import {defaults} from '../dist/settings.mjs';
import {draftRecord,savedRecords,exportRecords,parseRecordImport,mergeRecordImport} from '../dist/records.mjs';
const now='2026-10-20T13:35:00.000Z',a=draftRecord(defaults(),'Device A');
const local=savedRecords({records:[],lastOpenedId:null},a,a.state,now);
